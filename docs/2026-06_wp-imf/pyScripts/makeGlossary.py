def longtable(groups, caption, label, values=None, eqns=None, notes=None):
    withval = values is not None
    if withval and eqns:      # endogenous: equations + steady-state value columns
        width = "7.7cm"
    elif withval:             # parameters: value columns only
        width = "5.8cm"
    elif eqns:                # equations only
        width = "9.3cm"
    else:                     # exogenous
        width = "7.6cm"
    if withval:
        colspec = (r"@{}r@{\hskip 8pt}l >{\raggedright\arraybackslash}p{" + width
                   + r"} l r@{\hskip 12pt}r@{}")
        head = r"\# & Paper & Description & Model code & AE & EMDE \\"
        ncol = 6
    else:
        colspec = (r"@{}r@{\hskip 10pt}l >{\raggedright\arraybackslash}p{" + width
                   + r"} l@{}")
        head = r"\# & Paper & Description & Model code \\"
        ncol = 4
    lines = [
        HEADER,
        rf"\begin{{longtable}}{{{colspec}}}",
        rf"\caption{{{caption}}}\label{{{label}}}\\",
        r"\toprule", head, r"\midrule", r"\endfirsthead",
        rf"\multicolumn{{{ncol}}}{{c}}{{{{\tablename\ \thetable{{}} -- continued from previous page}}}}\\",
        r"\toprule", head, r"\midrule", r"\endhead",
        r"\midrule", rf"\multicolumn{{{ncol}}}{{r}}{{\textit{{continued on next page}}}}\\", r"\endfoot",
        r"\bottomrule", r"\endlastfoot",
    ]
    n = 0
    for gi, (title, rows) in enumerate(groups):
        if gi > 0:
            lines.append(r"\addlinespace[0.4em]")
        lines.append(rf"\multicolumn{{{ncol}}}{{@{{}}l}}{{\textit{{{title}}}}} \\")
        lines.append(r"\addlinespace[0.1em]")
        for paper, desc, model in rows:
            n += 1
            code = model.replace("_", r"\_")
            d = desc
            if notes and model in notes:
                d = d + notes[model]
            if eqns and model in eqns:
                d = d + r" \gloseq{" + eqns[model] + "}"
            if withval:
                vt = values.get(model, ("", ""))
                ae, em = vt[0], vt[1]
                if len(vt) > 2 and vt[2]:  # shade cells that differ (parameters table)
                    ae = r"\cellcolor{diffcell} " + ae
                    em = r"\cellcolor{diffcell} " + em
                lines.append(rf"{n} & {paper} & {d} & \texttt{{{code}}} & {ae} & {em} \\")
            else:
                lines.append(rf"{n} & {paper} & {d} & \texttt{{{code}}} \\")
    lines.append(r"\end{longtable}")
    return "\n".join(lines) + "\n"


def main():
    # AE/EMDE steady-state values (endogenous variables) and calibrated parameters.
    aess, emss = read_steady(AE_MODEL), read_steady(EM_MODEL)
    # Parameter-table values: read from params, but the three endogenously-calibrated
    # constants (omega, chiH, kappaprob) are model variables, so read their steady state.
    ae = {**aess, **read_params(AE_MODEL)}
    em = {**emss, **read_params(EM_MODEL)}
    pvals = {}
    for _, rows in PARAMETERS:
        for _paper, _desc, code in rows:
            if code in ae:
                a = fmt_val(ae[code])
                e = "--" if code in EMDE_DASH else fmt_val(em[code])
                pvals[code] = (a, e, a != e)  # third element: differs across AE/EMDE
    svals = {}
    for _, rows in ENDOGENOUS:
        for _paper, _desc, code in rows:
            if code in aess:
                svals[code] = (fmt_val(aess[code]), fmt_val(emss[code]))
    # Blue parenthetical notes for the endogenously calibrated parameters.
    CALIB = {
        "omega":     ("labor supply",         "L_t", "L"),
        "kappaprob": ("adoption probability",  "q_t", "q"),
    }
    pnotes = {code: rf"\calibnote{{targets steady-state {label} ${sym}={fmt_val(aess[tgt])}$}}"
              for code, (label, sym, tgt) in CALIB.items()}
    pnotes["chiH"] = r"\calibnote{solved from the steady-state education-time condition}"
    specs = [
        (ENDOGENOUS, "Endogenous Variables", "tab:glossEndo", "glossaryEndogenous.tex", svals, EQNS, None),
        (PARAMETERS, "Parameters",           "tab:glossParam", "glossaryParameters.tex", pvals, None, pnotes),
        (EXOGENOUS,  "Exogenous Variables (Shocks)", "tab:glossExo", "glossaryExogenous.tex", None, None, None),
    ]
    for groups, caption, label, fname, values, eqns, notes in specs:
        (OUT_DIR / fname).write_text(longtable(groups, caption, label, values, eqns, notes), encoding="utf-8")
        nrows = sum(len(rows) for _, rows in groups)
        extra = "" if values is None else " + AE/EMDE values"
        print(f"  Wrote {fname} ({nrows} rows{extra})")


if __name__ == "__main__":
    main()
