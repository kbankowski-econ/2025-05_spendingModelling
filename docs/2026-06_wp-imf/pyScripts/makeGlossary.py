def read_params(model):
    """Return {param_name: value} from the committed <model>_results.mat."""
    M = loadmat(MODELS_DIR / model / "Output" / f"{model}_results.mat")["M_"]
    names = [str(x[0]) for x in M["param_names"][0, 0][:, 0]]
    return dict(zip(names, M["params"][0, 0].ravel()))


def read_steady(model):
    """Return {endo_name: steady-state value} from the committed <model>_results.mat."""
    m = loadmat(MODELS_DIR / model / "Output" / f"{model}_results.mat")
    names = [str(x[0]) for x in m["M_"]["endo_names"][0, 0][:, 0]]
    return dict(zip(names, m["oo_"]["steady_state"][0, 0].ravel()))


def fmt_val(x):
    """Format at up to 3 decimal places (trailing zeros trimmed); fall back to
    significant figures only when 3 dp would round the value to zero."""
    x = float(x)
    if abs(x) < 1e-12:
        return "0"
    s = f"{x:.3f}"
    if float(s) == 0:            # too small for 3 dp -> keep significant figures
        s = f"{x:.3g}"
    return s.rstrip("0").rstrip(".") if "." in s else s

